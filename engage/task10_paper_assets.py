#!/usr/bin/env python3
"""Task 10: paper figures (vector PDF, 12.2 cm wide) and LaTeX tables, built only
from files in results/ (plus the dataset's meta/labels for the dataset table).

    python task10_paper_assets.py
Writes ../paper/figures/{pipeline,sweep,noise}.pdf and ../paper/tables/*.tex.
"""
import json
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyArrowPatch, FancyBboxPatch

from analysis import RESULTS, episode_records, scenario_takes
from engage.fuzzy import RULES

HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(HERE, "..", "paper", "figures")
TAB = os.path.join(HERE, "..", "paper", "tables")
W = 12.2 / 2.54
COL = {"it2": "#2a78d6", "type1": "#eb6834", "facing_only": "#1baf7a", "ref": "#8a8984",
       "ink": "#0b0b0b", "ink2": "#52514e", "fill": "#eef3fb", "fill2": "#f4f3ef"}
NAMES = {"gesture_only": "Gesture only", "nearest": "Nearest person", "facing_only": "Facing only$^\\dagger$",
         "distance_only": "Distance only$^\\dagger$", "logreg": "Logistic regression$^\\dagger$",
         "type1": "Type-1 engagement", "it2": "\\textbf{IT2 engagement (ours)}"}
ORDER = ["gesture_only", "nearest", "facing_only", "distance_only", "logreg", "type1", "it2"]

plt.rcParams.update({"font.size": 8, "font.family": "DejaVu Sans", "axes.spines.top": False,
                     "axes.spines.right": False, "axes.edgecolor": COL["ref"], "axes.labelcolor": COL["ink"],
                     "xtick.color": COL["ink2"], "ytick.color": COL["ink2"], "pdf.fonttype": 42,
                     "axes.linewidth": 0.6, "xtick.major.width": 0.6, "ytick.major.width": 0.6})


def J(name):
    return json.load(open(os.path.join(RESULTS, name + ".json")))


def pct(r, ci=True):
    s = f"{100 * r['p']:.0f}\\,\\% ({r['k']}/{r['n']})"
    return s + f" [{100 * r['lo']:.0f}--{100 * r['hi']:.0f}]" if ci else s


def write(name, body):
    os.makedirs(TAB, exist_ok=True)
    open(os.path.join(TAB, name + ".tex"), "w", encoding="utf-8").write(
        "% generated by engage/task10_paper_assets.py from engage/results/ - do not edit by hand\n" + body)


def savefig(fig, name):
    os.makedirs(FIG, exist_ok=True)
    fig.savefig(os.path.join(FIG, name + ".pdf"))
    fig.savefig(os.path.join(RESULTS, "paper_" + name + ".png"), dpi=200)
    plt.close(fig)


# ------------------------------------------------------------------ figures
def fig_pipeline():
    fig, ax = plt.subplots(figsize=(W, W * 0.37))
    ax.set_xlim(0, 100)
    ax.set_ylim(0, 40)
    ax.axis("off")

    def box(x, w, title, lines, fill, y=0.5, h=39):
        ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.3,rounding_size=1.2",
                                    fc=fill, ec=COL["ref"], lw=0.6))
        ax.text(x + w / 2, y + h - 2.5, title, ha="center", va="top", fontsize=7, weight="bold", color=COL["ink"])
        ax.text(x + w / 2, y + h - 8.5, "\n".join(lines), ha="center", va="top", fontsize=6,
                color=COL["ink2"], linespacing=1.45)

    def arrow(x0, x1, y=20):
        ax.add_patch(FancyArrowPatch((x0, y), (x1, y), arrowstyle="-|>", mutation_scale=7, lw=0.8,
                                     color=COL["ink2"], shrinkA=0, shrinkB=0))

    box(0.5, 14, "RGB-D", ["camera", "on the", "robot", "", "colour +", "depth"], COL["fill2"])
    box(17.5, 22, "Per person", ["pose (≤ 6) + tracking", "", r"distance $d,\ \sigma_d$", r"approach $v$",
                                 r"facing $f,\ \sigma_f$", "", "hands on a crop", r"$\rightarrow$ gesture $\ell$, conf $c$"],
        COL["fill2"])
    box(42.5, 17, "Layer 1", ["IT2 fuzzy", "engagement", "", r"FOU $= k\,\sigma$", "per person", "and frame", "",
                              r"$\rightarrow [E_{\mathrm{low}}, E_{\mathrm{high}}]$"], COL["fill"])
    box(62.5, 17, "Layer 2", ["accept if", r"$E_{\mathrm{low}} \geq \theta_E(\ell)$", r"and $c \geq \theta_c$", "",
                              "3-frame", "sustain"], COL["fill"])
    box(82.5, 17, "Arbitration", ["STOP wins,", "else the most", "engaged", "", r"$\rightarrow$ Move /", "StopMove"],
        COL["fill2"])
    for x0, x1 in ((15, 17.2), (39.9, 42.2), (59.9, 62.2), (79.9, 82.2)):
        arrow(x0, x1)
    fig.tight_layout(pad=0.1)
    savefig(fig, "pipeline")


def fig_sweep(an):
    fig, ax = plt.subplots(figsize=(W, W * 0.5))
    style = {"it2": ("IT2 engagement", COL["it2"], "-", "o"), "type1": ("Type-1 engagement", COL["type1"], "--", "s"),
             "facing_only": ("Facing only", COL["facing_only"], ":", "^")}
    for m, (lab, c, ls, mk) in style.items():
        cur = an["sweep"]["curves"][m]
        ax.plot([100 * a[1] for a in cur], [100 * a[2] for a in cur], ls, color=c, lw=1.4, label=lab)
        if m in ("it2", "type1"):
            o = an["operating_point"][m]
            ax.plot(100 * o[0]["p"], 100 * o[1]["p"], mk, color=c, ms=5.5, mec="white", mew=0.8, zorder=5)
    g = an["operating_point"]["gesture_only"]
    ax.plot(100 * g[0]["p"], 100 * g[1]["p"], "D", color=COL["ref"], ms=5, mec="white", mew=0.8)
    ax.annotate("gesture only", (100 * g[0]["p"], 100 * g[1]["p"]), xytext=(-5, -11), textcoords="offset points",
                ha="right", fontsize=6.5, color=COL["ink2"])
    ax.annotate(r"frozen $\theta_E$", (100 * an["operating_point"]["it2"][0]["p"], 100 * an["operating_point"]["it2"][1]["p"]),
                xytext=(10, -14), textcoords="offset points", fontsize=6.5, color=COL["ink2"],
                arrowprops=dict(arrowstyle="-", color=COL["ref"], lw=0.5))
    ax.set_xlabel("Bystander false-trigger rate (%)")
    ax.set_ylabel("Commander recall (%)")
    ax.set_xlim(0, 65)
    ax.set_ylim(0, 80)
    ax.grid(alpha=0.25, lw=0.4)
    ax.legend(frameon=False, loc="lower right", fontsize=7)
    fig.tight_layout(pad=0.3)
    savefig(fig, "sweep")


def fig_noise(an):
    fig, axs = plt.subplots(2, 2, figsize=(W, W * 0.66), sharey="row", sharex="col")
    lv = an["noise"]["levels"]
    series = (("type1", "Type-1", COL["type1"], "--", "s"), ("it2", "IT2 (σ updated)", COL["it2"], "-", "o"),
              ("it2_fixed_sigma", "IT2 (σ not updated)", COL["it2"], ":", "x"),
              ("facing_only", "Facing only", COL["facing_only"], ":", "^"))
    for col, var, unit in ((0, "facing", ""), (1, "distance", " (m)")):
        for row, key in ((0, "ft"), (1, "recall")):
            ax = axs[row, col]
            for m, lab, c, ls, mk in series:
                v = [an["noise"]["results"][var][str(s)][m] for s in lv[var]]
                ax.errorbar(lv[var], [100 * a[key + "_mean"] for a in v], yerr=[100 * a[key + "_sd"] for a in v],
                            fmt=ls, marker=mk, color=c, lw=1.1, ms=3.5, capsize=1.5, label=lab)
            if row:
                ax.set_xlabel(f"Noise s added to {var}{unit}")
            ax.grid(alpha=0.25, lw=0.4)
    axs[0, 0].set_ylabel("False triggers (%)")
    axs[1, 0].set_ylabel("Recall (%)")
    h, lab = axs[0, 0].get_legend_handles_labels()
    fig.legend(h, lab, loc="lower center", ncol=4, frameon=False, fontsize=6.5)
    fig.tight_layout(rect=(0, 0.07, 1, 1), pad=0.3)
    savefig(fig, "noise")


