def tab_dataset():
    eps, missed = episode_records(scenario_takes())
    metas = {}
    for t in scenario_takes():
        m = json.load(open(os.path.join(t, "meta.json")))
        metas[m["take"]] = m
    desc = {"S1": "single commander", "S2": "bystanders gesture to each other", "S3": "simultaneous gestures",
            "S4": "commander turns to a friend", "S5": "two commanders", "S6": "bystanders walk past"}
    rows, tot = [], [0, 0.0, 0, 0, 0, 0]
    for sc in ("S1", "S2", "S3", "S4", "S5", "S6"):
        tk = [n for n in metas if n.split("_")[1] == sc]
        mins = sum(metas[n]["duration_s"] for n in tk) / 60
        c = {l: sum(e["label"] == l for e in eps if e["scenario"] == sc) for l in "rnx"}
        mi = sum(missed[n] for n in tk)
        rows.append(f"{sc} & {desc[sc]} & {len(tk)} & {mins:.1f} & {c['r']} & {c['n']} & {c['x']} & {mi}\\\\")
        for i, v in enumerate((len(tk), mins, c["r"], c["n"], c["x"], mi)):
            tot[i] += v
    write("dataset", f"""\\begin{{table}}[t]
\\centering
\\caption{{Labelled data per scenario: takes, minutes, gesture episodes addressed to the robot ($r$), not
addressed ($n$), bad detections ($x$, excluded), and robot-directed gestures never detected (missed).}}
\\label{{tab:dataset}}
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{llcccccc}}
\\toprule
& Scenario & Takes & Min & $r$ & $n$ & $x$ & Missed\\\\
\\midrule
{chr(10).join(rows)}
\\midrule
& Total & {tot[0]} & {tot[1]:.1f} & {tot[2]} & {tot[3]} & {tot[4]} & {tot[5]}\\\\
\\bottomrule
\\end{{tabular}}
\\end{{table}}
""")


