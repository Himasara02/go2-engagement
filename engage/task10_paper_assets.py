def main():
    an, bl, st = J("analysis"), J("baselines"), J("stats")
    tab_gaze(J("gaze_mono"))
    fig_pipeline()
    fig_sweep(an)
    fig_noise(an)
    tab_main(bl, st)
    tab_rules()
    tab_stats(st)
    tab_uncertainty(an)
    tab_perception(J("perception"))
    tab_distance(J("distance"))
    tab_dataset()
    print("figures:", sorted(os.listdir(FIG)))
    print("tables:", sorted(os.listdir(TAB)))


if __name__ == "__main__":
    main()
