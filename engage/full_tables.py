#!/usr/bin/env python3
"""LaTeX tables for the CVPR paper from the full-dataset evaluation.

    python3 full_tables.py

Reads results/full/eval.json (full_eval.py). Writes ../../cvpr2027_paper/tables/{main,uncertainty}.tex
(generated: do not edit by hand). Standard library only.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
E = json.load(open(os.path.join(HERE, "results", "full", "eval.json")))
TAB = os.path.join(HERE, "..", "..", "cvpr2027_paper", "tables")
HDR = "% generated by go2-engagement/engage/full_tables.py from results/full/eval.json - do not edit by hand\n"
P = E["policies"]
WF = os.path.join(HERE, "results", "full_walking", "eval.json")
EW = json.load(open(WF)) if os.path.exists(WF) else None
PW = EW["policies"] if EW else None


def ci(r, best=False):
    v = f"{100 * r['p']:.1f}"
    return (rf"\textbf{{{v}}}" if best else v) + f" [{100 * r['lo']:.1f}--{100 * r['hi']:.1f}]"


def r2(m):
    v = E["sweep"]["recall_at_ft"].get(m, {}).get("0.02")
    return "--" if v is None else f"{100 * v:.0f}"


gates = ["facing_only", "gaze_only", "logreg", "type1", "type1_gaze", "it2", "it2_gaze"]
best_ft = min(gates, key=lambda m: P[m]["false_trigger"]["p"])
best_w = min(gates, key=lambda m: PW[m]["false_trigger"]["p"]) if PW else None


def wcols(m, untuned=False):
    if not PW:
        return r"\RES{--} & \RES{--}"
    v = EW["untuned"]["facing_only"]["0.50"] if untuned else PW[m]
    return f"{ci(v['false_trigger'], m == best_w and not untuned)} & {ci(v['recall'])}"
ROWS = [("gesture_only", "Gesture only"), None,
        ("distance_only", r"Distance only$^\dagger$"), ("facing_only", r"Facing only$^\dagger$"),
        ("gaze_only", r"Gaze only$^\dagger$"), ("logreg", r"Logistic regression$^\dagger$"), None,
        ("type1", "Type-1 gate"), ("type1_gaze", "Type-1 gate + gaze"), ("it2", "IT2 gate (ours)"),
        ("it2_gaze", r"\textbf{IT2 gate + gaze (ours)}")]
body = []
for row in ROWS:
    if row is None:
        body.append(r"\midrule")
        continue
    m, name = row
    body.append(f"{name:<34} & {ci(P[m]['false_trigger'], m == best_ft)} & {ci(P[m]['recall'])} & {r2(m)} "
                f"& {wcols(m)}\\\\")
    if m == "gesture_only":
        body.append(f"{'Nearest person':<34} & {ci(P['nearest']['false_trigger'])} & {ci(P['nearest']['recall'])} & -- "
                    f"& {wcols('nearest')}\\\\")
    if m == "facing_only":
        u = E["untuned"]["facing_only"]["0.50"]
        body.append(f"{'Facing only, untuned (0.5)':<34} & {ci(u['false_trigger'])} & {ci(u['recall'])} & -- "
                    f"& {wcols('facing_only', True)}\\\\")
n = E["episodes"]
th = lambda v: f"{v:,}".replace(",", "{,}")
main = HDR + rf"""\begin{{table*}}[t]
\centering\small
\setlength{{\tabcolsep}}{{5pt}}
\caption{{Main results on the {th(n['r'])} robot-directed and {th(n['n'])} bystander episodes of the 60 standing
recordings and the {th(EW['episodes']['r'])} and {th(EW['episodes']['n'])} episodes of the 21 walking recordings. FT: bystander false-trigger rate (lower is better). Recall: robot-directed episodes executed.
R@2: recall at FT\,$\le$\,2\pct\ on the operating curve. All in \%, 95\pct\ Wilson intervals in brackets.
$^\dagger$Threshold or model fitted leave-one-recording-out on labelled recordings (facing: 0.76 in every
fold); for the walking recordings they are fitted once on all standing recordings. ``Untuned'' uses the
natural threshold 0.5 without data. The rule-based gates use parameters frozen before data collection.}}
\label{{tab:main}}
\begin{{tabular}}{{@{{}}l ccc cc@{{}}}}
\toprule
& \multicolumn{{3}}{{c}}{{Robot standing}} & \multicolumn{{2}}{{c}}{{Robot walking}}\\
\cmidrule(lr){{2-4}}\cmidrule(l){{5-6}}
Policy & FT $\downarrow$ & Recall $\uparrow$ & R@2 $\uparrow$ & FT $\downarrow$ & Recall $\uparrow$\\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}
\end{table*}
"""
open(os.path.join(TAB, "main.tex"), "w").write(main)

S = E["splits"]
B = S["bins"]


def fr(v):
    return f"{100 * v['false_trigger']['p']:.0f} & {100 * v['recall']['p']:.0f}"


k = E["fou_k"]
unc = HDR + rf"""\begin{{table}}[t]
\centering\small
\setlength{{\tabcolsep}}{{3.5pt}}
\caption{{Where measured uncertainty matters. FT\,/\,recall (\%) at the frozen
operating point. Top: episodes split at the median measured uncertainty
($\sigma_f={S['medians']['facing_sigma']:.3f}$, $\sigma_d={S['medians']['distance_sigma']:.2f}$\,m).
Middle: FOU scale $k$ ($k=0$ is type-1). Bottom: monocular distance from shoulder width instead of depth.}}
\label{{tab:uncertainty}}
\begin{{tabular}}{{@{{}}lcccc@{{}}}}
\toprule
& \multicolumn{{2}}{{c}}{{Type-1}} & \multicolumn{{2}}{{c}}{{IT2}}\\
\cmidrule(lr){{2-3}}\cmidrule(l){{4-5}}
Episodes / setting & FT & Recall & FT & Recall\\
\midrule
$\sigma_f$ low  & {fr(B['facing σ']['low']['type1'])} & {fr(B['facing σ']['low']['it2'])}\\
$\sigma_f$ high & {fr(B['facing σ']['high']['type1'])} & {fr(B['facing σ']['high']['it2'])}\\
$\sigma_d$ low  & {fr(B['distance σ']['low']['type1'])} & {fr(B['distance σ']['low']['it2'])}\\
$\sigma_d$ high & {fr(B['distance σ']['high']['type1'])} & {fr(B['distance σ']['high']['it2'])}\\
\midrule
$k=0.5$ / $1$ / $2$ & & & \multicolumn{{2}}{{c}}{{{fr(k['0.5']).replace(' & ', '/')}\,;\,{fr(k['1']).replace(' & ', '/')}\,;\,{fr(k['2']).replace(' & ', '/')}}}\\
\midrule
Monocular distance & {100 * P['type1_mono']['false_trigger']['p']:.0f} & {100 * P['type1_mono']['recall']['p']:.0f} & {100 * P['it2_mono']['false_trigger']['p']:.0f} & {100 * P['it2_mono']['recall']['p']:.0f}\\
\bottomrule
\end{{tabular}}
\end{{table}}
"""
open(os.path.join(TAB, "uncertainty.tex"), "w").write(unc)
print("wrote tables/main.tex and tables/uncertainty.tex")
